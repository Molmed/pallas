import joblib
from pathlib import Path
import argparse
import mlflow
import dotenv
from helpers import (classifier_level_metrics,
                     class_level_metrics,
                     plot_precision_recall,
                     plot_confusion_matrix,
                     plot_per_class_calibration_curves)


description = """
Evaluates a model and optionally logs it to MLFlow.
"""

pallas_model_base_dir_help = """
The path to a pallas model base directory
where all trained models are stored. The script will look in
this directory for a subdirectory corresponding to the model being evaluated, and
then a model file named "rf_model.joblib".
"""

pallas_model_name_help = """
The name of the model being evaluated, e.g.
rf_DNAm_20260606_193214."""

predictions_base_dir_help = """
The path to a directory containing predictions
and labels generated by predict.py, excluding the model and dataset name.
"""

dataset_name_help = """
The name of the dataset being used to evaluate the model."""

output_dir_help = """
Directory to save the output."""

human_readable_title_help = """
A human-readable title for the evaluation,
e.g. "GEX model evaluated on the test set"
"""

enable_mlflow_help = """
Whether to enable MLFlow logging.
If enabled, the script will log the model and
evaluation metrics to MLFlow. Default is False.
MLFlow environment variables must be set for this to work.
"""


def parse_args():
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument(
        "--pallas_model_base_dir",
        type=str,
        required=True,
        help=pallas_model_base_dir_help,
    )
    parser.add_argument(
        "--pallas_model_name",
        type=str,
        required=True,
        help=pallas_model_name_help,
    )
    parser.add_argument(
        "--predictions_base_dir",
        type=str,
        required=True,
        help=predictions_base_dir_help,
    )
    parser.add_argument(
        "--dataset_name",
        type=str,
        required=True,
        help=dataset_name_help,
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        required=True,
        help=output_dir_help,
    )
    parser.add_argument(
        "--human_readable_title",
        type=str,
        required=False,
        help=human_readable_title_help,
    )
    parser.add_argument(
        "--enable_mlflow",
        type=bool,
        required=False,
        default=False,
        help=enable_mlflow_help,
    )
    return parser.parse_args()


def main():
    args = parse_args()

    model_name = args.pallas_model_name
    dataset_name = args.dataset_name
    # Create subdir in output dir for this dataset
    output_dir = Path(args.output_dir) / model_name / dataset_name
    output_dir.mkdir(parents=True, exist_ok=True)

    # Construct name of predictions files based on dataset name
    preds_dir = Path(args.predictions_base_dir) / model_name / dataset_name
    y_test_path = preds_dir / "y_test.joblib"
    y_pred_path = preds_dir / "y_pred.joblib"
    y_pred_proba_path = preds_dir / "y_pred_proba.joblib"

    # Load predictions and labels
    y_test = joblib.load(y_test_path)
    y_pred = joblib.load(y_pred_path)
    y_pred_proba = joblib.load(y_pred_proba_path)

    # Load model
    model_path = Path(
        args.pallas_model_base_dir) / model_name / "rf_model.joblib"
    model = joblib.load(model_path)

    print("Classifier-level metrics:")
    classifier_metrics_df = classifier_level_metrics(
        y_test,
        y_pred,
        y_pred_proba,
        model.classes_)
    print(classifier_metrics_df)
    classifier_metrics_path = Path(output_dir) / "classifier_level_metrics.csv"
    classifier_metrics_df.to_csv(classifier_metrics_path)

    print("\n\nClass-level metrics:")
    class_metrics_df = class_level_metrics(
        y_test,
        y_pred,
        y_pred_proba,
        model.classes_)
    print(class_metrics_df)
    class_metrics_path = Path(output_dir) / "class_level_metrics.csv"
    class_metrics_df.to_csv(class_metrics_path,
                            header=True,
                            index=True)

    confusion_matrix_path = Path(output_dir) / "confusion_matrix.svg"
    plot_confusion_matrix(y_test,
                          y_pred,
                          confusion_matrix_path)

    precision_recall_path = Path(output_dir) / "precision_recall.svg"
    if args.human_readable_title:
        title = args.human_readable_title
    else:
        title = f"Model {model_name} evaluated on dataset {dataset_name}"
    plot_precision_recall(
        class_metrics_df,
        title=title,
        save_path=precision_recall_path
    )

    plot_per_class_calibration_curves(
        y_test,
        y_pred_proba,
        model.classes_,
        save_path=output_dir / "calibration_curves.svg",
        title=args.human_readable_title,
        color_tsv_path=Path(__file__).resolve().parent.parent / "configs" / "class_colors.tsv"
    )

    if not args.enable_mlflow:
        return

    print("\n\nLogging to MLFlow...")
    dotenv.load_dotenv()
    with mlflow.start_run(run_name=args.human_readable_title):
        # Log each scalar as a metric
        classifier_metrics_dict = classifier_metrics_df["value"].to_dict()

        metrics_to_log = {}
        for metric_name, value in classifier_metrics_dict.items():
            metrics_to_log[metric_name] = float(value)

        mlflow.log_metrics(metrics_to_log)
        mlflow.log_artifact(str(classifier_metrics_path))
        mlflow.log_artifact(str(class_metrics_path))

        # --- Plots ---
        mlflow.log_artifact(str(confusion_matrix_path))
        mlflow.log_artifact(str(precision_recall_path))

        # Unpack signature from mlflow_signature.joblib
        signature = joblib.load(
            Path(args.pallas_model_base_dir) /
            model_name / "mlflow_signature.joblib")

        # --- Model ---
        mlflow.sklearn.log_model(sk_model=model,
                                 name=model_name,
                                 signature=signature)
        mlflow.log_params(model.get_params())

        # Optional: tag run with model/dataset names for easy filtering
        mlflow.set_tags({
            "dataset_name": dataset_name,
        })


if __name__ == "__main__":
    main()
